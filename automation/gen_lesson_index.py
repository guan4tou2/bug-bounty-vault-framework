#!/usr/bin/env python3
"""Frontmatter → LL 靜態索引投影；--check 只比對，不寫入。
檔名 full slug 是識別鍵；legacy id 可重複。type/status 分區以免歷史內容混進現行教訓。
實體 _archive/ 不加入現行投影。可從任何 cwd 執行。
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- AUTO-INDEX:START — generated by automation/gen_lesson_index.py, do not edit by hand -->"
END = "<!-- AUTO-INDEX:END -->"
INACTIVE_STATUSES = {"superseded", "deprecated", "merged", "archived", "disputed", "stub"}


def fm_of(text: str) -> dict:
    """Parse actual YAML; malformed/missing metadata is an error, never an empty record."""
    match = re.match(r"\A---\r?\n(.*?)\r?\n---(?:\r?\n|\Z)", text, re.S)
    if not match:
        raise ValueError("缺少完整 YAML frontmatter")
    try:
        fm = yaml.safe_load(match.group(1))
    except yaml.YAMLError as exc:
        raise ValueError(f"frontmatter YAML 無法解析：{exc}") from exc
    if not isinstance(fm, dict):
        raise ValueError("frontmatter 必須是 mapping")
    return fm


def load_lessons(lessons: Path) -> list[tuple[Path, dict]]:
    if not lessons.is_dir():
        raise ValueError(f"Lesson 目錄不存在：{lessons}")
    files = sorted(lessons.glob("LL-*.md"))
    if not files:
        raise ValueError(f"Lesson 目錄沒有 LL 檔：{lessons}（未執行有效掃描）")
    records, errors = [], []
    for path in files:
        try:
            fm = fm_of(path.read_text(encoding="utf-8"))
            if not isinstance(fm.get("id"), str) or not re.fullmatch(r"LL-[A-Za-z0-9]+", fm["id"]):
                raise ValueError("缺少或無效的 legacy id（預期 LL-NNN / LL-WNN）")
            records.append((path, fm))
        except (OSError, UnicodeError, ValueError) as exc:
            errors.append(f"{path.name}: {exc}")
    if errors:
        raise ValueError("\n".join(errors))
    return records


def section_of(fm: dict) -> str:
    if str(fm.get("status", "active")).lower() in INACTIVE_STATUSES:
        return "歷史與待釐清（非現行教訓）"
    if str(fm.get("type", "lesson")).lower() in {"reference", "rule"}:
        return "參考資料與規則（依 type 分流）"
    return "現行教訓"


def num_of(idv: str) -> str:
    return re.sub(r"([A-Za-z]*)0*(\d+)", r"\1\2", idv.removeprefix("LL-"))


def sortkey(idv: str):
    token = idv.removeprefix("LL-")
    if token.isdigit():
        return (0, int(token), "")
    match = re.fullmatch(r"([A-Za-z]+)0*(\d+)", token)
    return (1, int(match[2]), match[1]) if match else (2, 0, token)


def render_index(records: list[tuple[Path, dict]]) -> str:
    sections = ("現行教訓", "參考資料與規則（依 type 分流）", "歷史與待釐清（非現行教訓）")
    lines = [START]
    for section in sections:
        rows = [(path, fm) for path, fm in records if section_of(fm) == section]
        if not rows:
            continue
        lines.extend(["", f"### {section}", ""])
        for path, fm in sorted(rows, key=lambda row: (sortkey(row[1]["id"]), row[0].name)):
            label = " ".join(str(fm.get("summary") or fm.get("title") or path.stem).splitlines())
            suffix = ""
            if section != "現行教訓":
                status = fm.get("status")
                suffix = f" — type: {fm.get('type', 'lesson')}" + (f" · status: {status}" if status else "")
            lines.append(f"- #{num_of(fm['id'])} [[{path.stem}|{label}]]{suffix}")
    return "\n".join(lines + ["", END])


def replace_index(text: str, block: str) -> str:
    starts, ends = text.count(START), text.count(END)
    if starts == ends == 1 and text.index(START) < text.index(END):
        start, end = text.index(START), text.index(END) + len(END)
        return text[:start] + block + text[end:]
    if starts or ends:
        raise ValueError("AUTO-INDEX 標記缺失、順序錯誤或重複；拒絕覆寫")
    heading = "## 全文索引(直接列表)"
    if text.count(heading) != 1:
        raise ValueError("找不到唯一全文索引標題或 AUTO-INDEX 標記")
    start = text.index(heading) + len(heading)
    next_heading = re.search(r"^## ", text[start:], re.M)
    end = start + next_heading.start() if next_heading else len(text)
    return text[:start] + "\n\n" + block + "\n\n" + text[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    main_file = ROOT / "09 - Knowledge Base/Lessons Learned.md"
    try:
        records = load_lessons(main_file.parent / "Lessons")
        text = main_file.read_text(encoding="utf-8")
        new_text = replace_index(text, render_index(records))
        if args.check:
            if new_text != text:
                print("[gen_lesson_index] 索引與 frontmatter 不同步 — "
                      "跑 automation/uvrun python3 automation/gen_lesson_index.py 重生")
                return 1
            print(f"[gen_lesson_index] 索引同步 ✓（{len(records)} 條，依 type/status 分流）")
        else:
            main_file.write_text(new_text, encoding="utf-8")
            print(f"[gen_lesson_index] 生成 {len(records)} 條（依 type/status 分流）")
        return 0
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"[gen_lesson_index] ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
